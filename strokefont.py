_ADVANCE = 8.0  # glyph pitch on the 6-wide grid


def text(s, x, y, size, spacing=1.0):
    """Polylines for `s`, left-aligned, cap height `size`, baseline at `y`."""
    k = size / 10.0
    out = []
    cx = x
    for ch in s.upper() if s.upper() in _G or True else s:
        glyph = _G.get(ch, _G.get(ch.upper(), _G[" "]))
        for poly in glyph:
            out.append(([(cx + px * k, y - size + py * k) for px, py in poly], False))
        cx += _ADVANCE * k * spacing
    return out


def width(s, size, spacing=1.0):
    return len(s) * _ADVANCE * (size / 10.0) * spacing
